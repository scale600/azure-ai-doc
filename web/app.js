/* Runtime config injected at deploy time (see config.example.js).
   `window.APP_CONFIG` is set by config.js, which is generated by CI from
   GitHub Secrets and is NOT committed. */
"use strict";

const cfg = window.APP_CONFIG || {};
const API_BASE = cfg.functionAppUrl || "";
const API_KEY = cfg.apiKey || "";

const $ = (sel) => document.querySelector(sel);

async function api(path, options = {}) {
  const headers = Object.assign(
    { "Content-Type": "application/json", "x-api-key": API_KEY },
    options.headers || {}
  );
  const res = await fetch(`${API_BASE}${path}`, Object.assign({}, options, { headers }));
  const text = await res.text();
  const body = text ? JSON.parse(text) : {};
  if (!res.ok) {
    throw new Error(body.error || `HTTP ${res.status}`);
  }
  return body;
}

function statusBadge(status) {
  const cls = {
    UPLOADED: "badge-gray",
    PROCESSING: "badge-blue",
    COMPLETED: "badge-green",
    FAILED: "badge-red",
    REJECTED: "badge-red",
    REPROCESSING: "badge-blue",
  }[status] || "badge-gray";
  return `<span class="badge ${cls}">${status}</span>`;
}

function renderList(docs) {
  const tbody = $("#doc-list");
  if (!docs.length) {
    tbody.innerHTML = '<tr><td colspan="5" class="empty">No documents yet</td></tr>';
    return;
  }
  tbody.innerHTML = docs
    .map(
      (d) => `
      <tr>
        <td>${escapeHtml(d.fileName)}</td>
        <td>${escapeHtml(d.documentType || "—")}</td>
        <td>${statusBadge(d.status)}</td>
        <td>${escapeHtml(d.uploadedAt ? new Date(d.uploadedAt).toLocaleString() : "—")}</td>
        <td><button class="link" data-id="${d.documentId}">View</button></td>
      </tr>`
    )
    .join("");

  tbody.querySelectorAll("button.link").forEach((btn) =>
    btn.addEventListener("click", () => showDetail(btn.dataset.id))
  );
}

function renderDetail(d) {
  const body = $("#detail-body");
  const fields = d.keyFields
    ? Object.entries(d.keyFields)
        .map(([k, v]) => `<li><b>${escapeHtml(k)}</b>: ${escapeHtml(String(v))}</li>`)
        .join("")
    : "";
  const risks = (d.riskFlags || []).map((r) => `<li>${escapeHtml(r)}</li>`).join("");
  const missing = (d.missingFields || []).map((m) => `<li>${escapeHtml(m)}</li>`).join("");

  body.innerHTML = `
    <div class="detail-grid">
      <div><b>Status</b></div><div>${statusBadge(d.status)}</div>
      <div><b>Classification</b></div><div>${escapeHtml(d.classification || "—")}</div>
      <div><b>Confidence</b></div><div>${d.confidence != null ? d.confidence.toFixed(2) : "—"}</div>
      <div><b>Model</b></div><div>${escapeHtml(d.modelName || "—")}</div>
    </div>
    <h3>Summary</h3>
    <p>${escapeHtml(d.summary || "—")}</p>
    ${fields ? `<h3>Key fields</h3><ul>${fields}</ul>` : ""}
    ${risks ? `<h3>Risk flags</h3><ul class="risk">${risks}</ul>` : ""}
    ${missing ? `<h3>Missing fields</h3><ul class="missing">${missing}</ul>` : ""}
  `;
}

function escapeHtml(s) {
  return String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

async function refreshList() {
  try {
    const data = await api("/api/documents");
    renderList(data.documents || []);
  } catch (e) {
    $("#doc-list").innerHTML = `<tr><td colspan="5" class="empty">Error: ${escapeHtml(
      e.message
    )}</td></tr>`;
  }
}

async function showDetail(id) {
  try {
    const d = await api(`/api/documents/${id}`);
    $("#detail-card").hidden = false;
    renderDetail(d);
  } catch (e) {
    alert(`Failed to load document: ${e.message}`);
  }
}

async function upload(e) {
  e.preventDefault();
  const fileInput = $("#file-input");
  const file = fileInput.files[0];
  if (!file) return;

  const status = $("#upload-status");
  status.hidden = false;
  status.textContent = "Uploading…";

  const form = new FormData();
  form.append("file", file);
  const hint = $("#type-select").value;
  if (hint) form.append("document_type", hint);

  try {
    const res = await fetch(`${API_BASE}/api/documents`, {
      method: "POST",
      headers: { "x-api-key": API_KEY },
      body: form,
    });
    const body = await res.json();
    if (!res.ok) throw new Error(body.error || `HTTP ${res.status}`);
    status.textContent = `Accepted (id ${body.documentId}). Processing…`;
    fileInput.value = "";
    pollUntilDone(body.documentId);
  } catch (err) {
    status.textContent = `Upload failed: ${err.message}`;
  }
}

async function pollUntilDone(id, attempts = 0) {
  if (attempts > 30) {
    refreshList();
    return;
  }
  try {
    const d = await api(`/api/documents/${id}`);
    if (d.status === "COMPLETED" || d.status === "FAILED") {
      $("#upload-status").textContent = `Done: ${d.status}`;
      refreshList();
      return;
    }
  } catch (_) {
    /* transient — keep polling */
  }
  setTimeout(() => pollUntilDone(id, attempts + 1), 2000);
}

$("#upload-form").addEventListener("submit", upload);
refreshList();
